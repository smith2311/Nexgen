"""Vendor x RFI price-premium heatmap for the quote-comparison dashboard.

The analytical question this answers, which no other panel on that page does:
*across every RFI, who is consistently competitive and who is consistently
expensive?* The per-request tables show one RFI at a time and the AI panel gives
prose; neither shows the pattern across the whole board.

**The cell value is a premium, not a price.** Raw totals cannot be compared
across RFIs — a national warehousing deal and a single-lane courier quote differ
by orders of magnitude, so a matrix of raw numbers would just be a map of RFI
size. Each cell is instead ``vendor_total / cheapest_total`` for that RFI,
expressed as a percentage above the best bid. 0% is the winner; +35% is a third
dearer than the winner. That normalises every column onto one comparable scale.

**Currencies are never mixed.** ``VendorBid.currency`` varies and this module has
no FX table, so a USD bid and an INR bid are not comparable at all. The premium
is computed strictly within one currency for one RFI. When an RFI received bids
in more than one currency it is *split into one column per currency* rather than
silently compared — the column header carries the currency, and a note says why.

**The colour is a validated sequential ramp**, five steps of one hue, light→dark,
generated because premium is a *magnitude* (one direction, from a meaningful
floor of 0%). Not a rainbow, not a diverging pair — there is no meaningful
midpoint in "how much more than the cheapest". The ramp is a light warm one,
soft peach → medium ochre, generated by holding
one OKLCH hue and stepping lightness rather than by picking hex codes off a
palette — hand-picked warm scales drift in hue as they darken (Tailwind's amber
measures 47 degrees end to end) and stop being one hue.

Checked with the dataviz validator rather than by eye: monotone lightness,
every adjacent ΔL >= 0.06, hue spread 7 degrees, and one label ink (#241404)
clearing 4.5:1 on all five steps — 13.5:1 at the light end down to 5.1:1 at the
dark end.

The lightest step sits at 1.32:1 against white, below the 2:1 floor that
applies to an *ordinal* ramp. That is deliberate and allowed here: this is
sequential encoding of a continuous magnitude, where the lightest step means
"near zero premium" and is meant to recede toward the surface. A no-bid cell is
told apart by its dashed border, not by tint.

Two things were measured and rejected. A literal traffic light (green → lime →
amber → orange → red): 56-58 degrees of hue spread, and green-vs-red is the one
pair red-green colour blindness cannot separate. And a light ramp built from
adjacent Tailwind amber steps: adjacent ΔL of only 0.038-0.046, so the bands
were indistinguishable — which defeats the point of banding at all.

**The winner is a status, not a ramp step.** 0% is not "the lightest amount of
premium", it is the outcome "this vendor won the round", so it is painted in
the module's own success green and carries a marker dot and its own legend key
alongside the printed 0.0%. Colour is never the only channel: every cell prints
its number.
"""

from __future__ import annotations

#: Validated sequential ramp — orange, light→dark. Blue is already the module's
#: sequential hue (the Insights activity heatmap), and the palette rule is that
#: a second simultaneous sequential context takes the next slot's hue. Warm also
#: matches the convention that cost pressure reads hot.
#:
#: Each step carries the ink that clears 4.5:1 *on that step*, computed rather
#: than eyeballed: the crossover sits between steps 3 and 4, so a single text
#: colour would fail at one end or the other.
HEAT_STEPS: tuple[tuple[str, str], ...] = (
    ("#FBDBB0", "#241404"),   # 13.48:1
    ("#F3BF7F", "#241404"),   # 10.68:1
    ("#E8A557", "#241404"),  # 8.46:1
    ("#D29138", "#241404"),  # 6.67:1
    ("#BB7C1F", "#241404"),  # 5.11:1
)

#: The winner's fill. VendorLink's own success tint (--vl-green-tint / -ink),
#: so the cell matches every other "this one won" marker in the module and
#: stays as light as the ramp beside it. 8.30:1.
WINNER_BG = "#DCFCE7"
WINNER_INK = "#14532D"

#: Premium thresholds, in percent above the cheapest bid, mapped onto the ramp.
#: Chosen as procurement bands rather than equal quantiles: "within 5% of the
#: best" and "more than half again" are decisions, whereas a quantile split
#: would move the boundaries every time the data changed.
PREMIUM_BANDS: tuple[tuple[float, str], ...] = (
    (5.0, "within 5%"),
    (15.0, "5-15% over"),
    (30.0, "15-30% over"),
    (50.0, "30-50% over"),
    (float("inf"), "over 50%"),
)

#: Cap on columns rendered. Beyond this the grid stops being readable and starts
#: being a texture; the newest RFIs are kept and the drop is reported on screen
#: rather than left silent.
MAX_COLUMNS = 14


def _band(premium_pct: float) -> int:
    """0-based ramp index for a premium percentage."""
    for index, (ceiling, _label) in enumerate(PREMIUM_BANDS):
        if premium_pct < ceiling:
            return index
    return len(PREMIUM_BANDS) - 1


def build(rows) -> dict:
    """Assemble the matrix from ``bid_analytics``' own row dicts.

    ``rows`` is the ``data`` list that view already built — each entry holding a
    ``request`` and its ``vendor_groups`` (with ``best.total_cost`` and
    ``currency`` already computed by ``_vendor_bid_groups``). Reusing it means
    the heatmap cannot disagree with the tables underneath it, and costs no
    extra query.
    """
    # One column per (request, currency). dict preserves insertion order, and
    # `rows` arrives newest-first, so columns stay in that order.
    columns: dict = {}
    vendors: dict = {}

    for row in rows:
        request = row["request"]
        for group in row["vendor_groups"]:
            total = group["best"].total_cost
            if not total or total <= 0:
                # A bid with no costs filled in is not a quote of zero — it is
                # an incomplete draft, and averaging it in would invent a
                # winner that undercuts everyone.
                continue
            key = (request.pk, group["currency"])
            column = columns.setdefault(key, {
                "request": request,
                "currency": group["currency"],
                "bids": {},
            })
            name = group["vendor_name"] or "—"
            # Keep the vendor's own best bid if they submitted several.
            if name not in column["bids"] or total < column["bids"][name]:
                column["bids"][name] = total
            vendors[name] = vendors.get(name, 0) + 1

    # Drop columns with a single bidder: a premium against yourself is always
    # 0%, which paints a misleadingly perfect cell.
    comparable = {key: col for key, col in columns.items() if len(col["bids"]) > 1}
    dropped_single = len(columns) - len(comparable)

    truncated = 0
    if len(comparable) > MAX_COLUMNS:
        truncated = len(comparable) - MAX_COLUMNS
        comparable = dict(list(comparable.items())[:MAX_COLUMNS])

    # An RFI that drew bids in more than one currency now occupies several
    # columns; flag it so the split is explained rather than looking like
    # duplicate columns.
    per_request: dict = {}
    for request_pk, _currency in comparable:
        per_request[request_pk] = per_request.get(request_pk, 0) + 1
    split_requests = sum(1 for count in per_request.values() if count > 1)

    # Vendors ordered by how often they appear, so the densest rows sit together
    # and the sparse tail does not break up the pattern.
    ordered_vendors = [
        name for name, _count in
        sorted(vendors.items(), key=lambda item: (-item[1], item[0].lower()))
        if any(name in col["bids"] for col in comparable.values())
    ]

    column_meta, cell_lookup = [], {}
    for (request_pk, currency), column in comparable.items():
        cheapest = min(column["bids"].values())
        request = column["request"]
        column_meta.append({
            "request_pk": request_pk,
            "currency": currency,
            "subject": request.subject or f"RFI #{request_pk}",
            "country": request.country,
            "created": request.created_at,
            "bidders": len(column["bids"]),
            "cheapest": cheapest,
            "multi_currency": per_request.get(request_pk, 0) > 1,
        })
        for name, total in column["bids"].items():
            premium = (total / cheapest - 1) * 100
            cell_lookup[(name, request_pk, currency)] = {
                "total": total,
                "premium": premium,
                "level": _band(premium),
                "is_best": premium < 0.01,
            }

    grid = []
    for name in ordered_vendors:
        cells, wins, premiums = [], 0, []
        for meta in column_meta:
            cell = cell_lookup.get((name, meta["request_pk"], meta["currency"]))
            if cell is None:
                cells.append({"has_bid": False})
                continue
            if cell["is_best"]:
                wins += 1
            premiums.append(cell["premium"])
            # The winner is painted as a status, not as ramp step 0 — see the
            # module docstring.
            if cell["is_best"]:
                step_bg, step_ink = WINNER_BG, WINNER_INK
            else:
                step_bg, step_ink = HEAT_STEPS[cell["level"]]
            cells.append({
                "has_bid": True,
                "premium": cell["premium"],
                "premium_label": ("best" if cell["is_best"] else f"+{cell['premium']:.0f}%"),
                "level": cell["level"],
                "band": PREMIUM_BANDS[cell["level"]][1],
                "bg": step_bg,
                "ink": step_ink,
                "is_best": cell["is_best"],
                "total": cell["total"],
                "currency": meta["currency"],
                "subject": meta["subject"],
            })
        grid.append({
            "vendor": name,
            "cells": cells,
            "bids": len(premiums),
            "wins": wins,
            # Mean premium across the RFIs this vendor actually bid on — the
            # row's one-number summary. Averaged over their own bids, not over
            # every column, so a vendor who bid twice is not penalised for the
            # twelve they were not invited to.
            "avg_premium": round(sum(premiums) / len(premiums), 1) if premiums else None,
        })
        # The row summary is shaded on the same scale as the cells, so a
        # vendor's overall standing reads at a glance down the last column.
        # Paint decided here rather than in the template: the winner/ramp split
        # is a rule about the data, not a formatting detail.
        average = grid[-1]["avg_premium"]
        if average is None:
            grid[-1]["avg_bg"], grid[-1]["avg_ink"] = "", ""
        elif average < 0.01:
            grid[-1]["avg_bg"], grid[-1]["avg_ink"] = WINNER_BG, WINNER_INK
        else:
            grid[-1]["avg_bg"], grid[-1]["avg_ink"] = HEAT_STEPS[_band(average)]

    # Headline figures for the panel's metric cards. Computed here so the
    # template does no arithmetic and the Excel export can report the same
    # numbers as the screen.
    #
    # The median is taken over losing bids only: with the winners' zeros
    # included it would be dragged toward 0% and stop answering the question it
    # is there for, which is "when you are not the cheapest, by how much do you
    # normally miss?". Median rather than mean because one 300% outlier should
    # not move it.
    losing = sorted(
        cell["premium"]
        for row in grid for cell in row["cells"]
        if cell.get("has_bid") and not cell["is_best"]
    )
    if losing:
        middle = len(losing) // 2
        median_premium = round(
            losing[middle] if len(losing) % 2
            else (losing[middle - 1] + losing[middle]) / 2,
            1,
        )
    else:
        median_premium = None

    return {
        "has_data": bool(grid and column_meta),
        "columns": column_meta,
        "rows": grid,
        "winner_count": sum(row["wins"] for row in grid),
        "median_premium": median_premium,
        "currencies": sorted({meta["currency"] for meta in column_meta if meta["currency"]}),
        "country_count": len({meta["country"] for meta in column_meta if meta["country"]}),
        "steps": [
            {"bg": bg, "ink": ink, "label": PREMIUM_BANDS[index][1]}
            for index, (bg, ink) in enumerate(HEAT_STEPS)
        ],
        "vendor_count": len(grid),
        "column_count": len(column_meta),
        "truncated": truncated,
        "dropped_single": dropped_single,
        "split_requests": split_requests,
    }
